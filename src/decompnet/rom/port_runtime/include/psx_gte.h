/* Host override of the export's psx_gte.h (force-included with -include, so common.h's own `#include "psx_gte.h"`
 * finds this include guard already defined). The same macro names and operand conventions as the original, which is
 * MIT (Copyright (c) 2022 Decompollaborate; names from Rabbitizer's r3000gte/gte_macros.h): every GTE instruction
 * becomes a call into the software GTE in psx/gte.c. No system headers here: these lines land in every game file. */
#ifndef DECOMP_PSX_GTE_H
#define DECOMP_PSX_GTE_H

int psx_gte_mfc2(int reg);
int psx_gte_cfc2(int reg);
void psx_gte_mtc2(int reg, int value);
void psx_gte_ctc2(int reg, int value);
void psx_gte_op(unsigned int word);

#define PSX_GTE_VAL(v) ((int)(long)(v))

#define gte_RTPS() psx_gte_op(0x4A180001)
#define gte_nRTPS() psx_gte_op(0x4A180001)
#define gte_rtps() gte_nRTPS()
#define gte_RTPT() psx_gte_op(0x4A280030)
#define gte_nRTPT() psx_gte_op(0x4A280030)
#define gte_rtpt() gte_nRTPT()
#define gte_DPCL() psx_gte_op(0x4A680029)
#define gte_nDPCL() psx_gte_op(0x4A680029)
#define gte_dpcl() gte_nDPCL()
#define gte_DPCS() psx_gte_op(0x4A780010)
#define gte_nDPCS() psx_gte_op(0x4A780010)
#define gte_dpcs() gte_nDPCS()
#define gte_DPCT() psx_gte_op(0x4AF8002A)
#define gte_nDPCT() psx_gte_op(0x4AF8002A)
#define gte_dpct() gte_nDPCT()
#define gte_INTPL() psx_gte_op(0x4A980011)
#define gte_nINTPL() psx_gte_op(0x4A980011)
#define gte_intpl() gte_nINTPL()
#define gte_NCS() psx_gte_op(0x4AC8041E)
#define gte_nNCS() psx_gte_op(0x4AC8041E)
#define gte_ncs() gte_nNCS()
#define gte_NCT() psx_gte_op(0x4AD80420)
#define gte_nNCT() psx_gte_op(0x4AD80420)
#define gte_nct() gte_nNCT()
#define gte_NCDS() psx_gte_op(0x4AE80413)
#define gte_nNCDS() psx_gte_op(0x4AE80413)
#define gte_ncds() gte_nNCDS()
#define gte_NCDT() psx_gte_op(0x4AF80416)
#define gte_nNCDT() psx_gte_op(0x4AF80416)
#define gte_ncdt() gte_nNCDT()
#define gte_NCCS() psx_gte_op(0x4B08041B)
#define gte_nNCCS() psx_gte_op(0x4B08041B)
#define gte_nccs() gte_nNCCS()
#define gte_NCCT() psx_gte_op(0x4B18043F)
#define gte_nNCCT() psx_gte_op(0x4B18043F)
#define gte_ncct() gte_nNCCT()
#define gte_CDP() psx_gte_op(0x4B280414)
#define gte_nCDP() psx_gte_op(0x4B280414)
#define gte_cdp() gte_nCDP()
#define gte_NCLIP() psx_gte_op(0x4B400006)
#define gte_nNCLIP() psx_gte_op(0x4B400006)
#define gte_nclip() gte_nNCLIP()
#define gte_AVSZ3() psx_gte_op(0x4B58002D)
#define gte_nAVSZ3() psx_gte_op(0x4B58002D)
#define gte_avsz3() gte_nAVSZ3()
#define gte_AVSZ4() psx_gte_op(0x4B68002E)
#define gte_nAVSZ4() psx_gte_op(0x4B68002E)
#define gte_avsz4() gte_nAVSZ4()
#define gte_SQR(sf) psx_gte_op(0x4AA00428 | (((sf) & 1) << 19))
#define gte_nSQR(sf) gte_SQR(sf)
#define gte_sqr(sf) gte_nSQR(sf)
#define gte_OP(sf) psx_gte_op(0x4B70000C | (((sf) & 1) << 19))
#define gte_nOP(sf) gte_OP(sf)
#define gte_op(sf) gte_nOP(sf)
#define gte_GPF(sf) psx_gte_op(0x4B90003D | (((sf) & 1) << 19))
#define gte_nGPF(sf) gte_GPF(sf)
#define gte_gpf(sf) gte_nGPF(sf)
#define gte_GPL(sf) psx_gte_op(0x4BA0003E | (((sf) & 1) << 19))
#define gte_nGPL(sf) gte_GPL(sf)
#define gte_gpl(sf) gte_nGPL(sf)
#define gte_MVMVA(sf,mx,v,cv,lm) psx_gte_op(0x4A400012 | (((sf)&1)<<19) | (((mx)&3)<<17) | (((v)&3)<<15) | (((cv)&3)<<13) | (((lm)&1)<<10))
#define gte_nMVMVA(sf,mx,v,cv,lm) gte_MVMVA(sf,mx,v,cv,lm)
#define gte_mvmva(sf,mx,v,cv,lm) gte_nMVMVA(sf,mx,v,cv,lm)

#define gte_mfc2(reg) psx_gte_mfc2((reg) & 31)
#define gte_cfc2(reg) psx_gte_cfc2((reg) & 31)
#define gte_mtc2(reg,value) psx_gte_mtc2((reg) & 31, PSX_GTE_VAL(value))
#define gte_ctc2(reg,value) psx_gte_ctc2((reg) & 31, PSX_GTE_VAL(value))
#define gte_lwc2(reg,p) psx_gte_mtc2((reg) & 31, *(const int *)(p))
#define gte_swc2(reg,p) (*(int *)(p) = psx_gte_mfc2((reg) & 31))
#define gte_ldv0(p) do { gte_lwc2(0, (const int *)(p)); gte_lwc2(1, (const int *)(p) + 1); } while (0)
#define gte_ldv1(p) do { gte_lwc2(2, (const int *)(p)); gte_lwc2(3, (const int *)(p) + 1); } while (0)
#define gte_ldv2(p) do { gte_lwc2(4, (const int *)(p)); gte_lwc2(5, (const int *)(p) + 1); } while (0)
#define gte_ldv3(p0,p1,p2) do { gte_ldv0(p0); gte_ldv1(p1); gte_ldv2(p2); } while (0)
#define gte_ldrgb(p) gte_lwc2(6,p)
#define gte_lddp(value) gte_mtc2(8,value)
#define gte_stsxy(p) gte_swc2(14,p)
#define gte_stsxy0(p) gte_swc2(12,p)
#define gte_stsxy1(p) gte_swc2(13,p)
#define gte_stsxy2(p) gte_swc2(14,p)
#define gte_stsxy3(p0,p1,p2) do { gte_swc2(12,p0); gte_swc2(13,p1); gte_swc2(14,p2); } while (0)
#define gte_stsz(p) gte_swc2(19,p)
#define gte_stsz3(p0,p1,p2) do { gte_swc2(17,p0); gte_swc2(18,p1); gte_swc2(19,p2); } while (0)
#define gte_stotz(p) gte_swc2(7,p)
#define gte_strgb(p) gte_swc2(22,p)
#define gte_stflg(p) (*(int *)(p) = psx_gte_cfc2(31))
#define gte_rtv0() gte_nMVMVA(1,0,0,3,0)
#define gte_rtv0tr() gte_nMVMVA(1,0,0,0,0)

#define gte_CC() psx_gte_op(0x4B38041C)
#define gte_nCC() psx_gte_op(0x4B38041C)
#define gte_cc() gte_nCC()
#define gte_dcpl() gte_nDPCL()
#define gte_gpf_lm(sf,lm) psx_gte_op(0x4B90003D | (((sf)&1)<<19) | (((lm)&1)<<10))
#define gte_gpl_lm(sf,lm) psx_gte_op(0x4BA0003E | (((sf)&1)<<19) | (((lm)&1)<<10))
#define gte_op_lm(sf,lm) psx_gte_op(0x4B70000C | (((sf)&1)<<19) | (((lm)&1)<<10))

#endif
