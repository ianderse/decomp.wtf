/* The port's entry: a window, PS1 RAM with the game's image in it, then the game's main on a stack below 4 GB. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <sys/mman.h>
#include <unistd.h>

#include "psx_runtime.h"

#define GAME_STACK_SIZE (8u << 20)

static void *low_stack(void) {
    static const uintptr_t tries[] = {0x60000000u, 0x50000000u, 0x40000000u, 0x70000000u, 0x30000000u};
    size_t i;
    for (i = 0; i < sizeof tries / sizeof tries[0]; i++) {
        void *p = mmap((void *)tries[i], GAME_STACK_SIZE, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANON, -1, 0);
        if (p == MAP_FAILED) continue;
        if ((uintptr_t)p + GAME_STACK_SIZE <= 0x100000000ull) return (char *)p + GAME_STACK_SIZE;
        munmap(p, GAME_STACK_SIZE);
    }
    return NULL;
}

static void on_stop(int sig) {
    psx_log("psx: %s after the time PSX_TIMEOUT gave\n", sig == SIGALRM ? "stopped" : "terminated");
    psx_exit_report();
    _exit(124);
}

static void run_main(void) {
    psx_log("psx: calling the game's main, %s\n", psx_config.main_name);
    psx_config.main_fn();
    psx_log("psx: %s returned\n", psx_config.main_name);
}

int main(int argc, char **argv) {
    const char *headless = getenv("PSX_HEADLESS");
    void *top;
    (void)argc; (void)argv;
    setvbuf(stdout, NULL, _IOLBF, 0);
    psx_log("psx: %s, generated by decomp.wtf's port export\n", psx_config.title);
    psx_dispatch_init();
    psx_ram_init();
    if (headless && *headless && strcmp(headless, "0") != 0) psx_log("psx: headless (PSX_HEADLESS)\n");
    else if (!host_init(psx_config.title, 640, 480)) psx_log("psx: no window (%s); running headless\n", host_name());
    else psx_log("psx: window 640x480 (%s)\n", host_name());
    atexit(psx_exit_report);
    signal(SIGTERM, on_stop);
    signal(SIGINT, on_stop);
    if (getenv("PSX_TIMEOUT") && atoi(getenv("PSX_TIMEOUT")) > 0) {
        signal(SIGALRM, on_stop);
        alarm((unsigned)atoi(getenv("PSX_TIMEOUT")));
    }
    if ((uintptr_t)(void *)main >= 0x100000000ull)
        psx_log("psx: warning: host code is above 4 GB (%p): function addresses stored in 32-bit fields truncate\n",
                (void *)main);
    top = low_stack();
    if (top) {
        psx_log("psx: game stack at %p (below 4 GB)\n", (char *)top - GAME_STACK_SIZE);
        psx_call_on_stack(run_main, top);
    } else {
        psx_log("psx: no stack below 4 GB; running on the host stack\n");
        run_main();
    }
    host_shutdown();
    return 0;
}
