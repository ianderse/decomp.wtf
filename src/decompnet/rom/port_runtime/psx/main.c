/* The port's entry: a window, PS1 RAM with the game's image in it, then the game's main on a stack in the window. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <sys/mman.h>
#include <unistd.h>

#include "psx_runtime.h"

/* the game's stack in the window, so its locals' addresses are PS1 addresses (sp 0x6000xxxx): PSX_STACK_TOP, or
 * lower if something else is there (nothing should be) */
static void *game_stack(uint32_t *bottom) {
    static const uint32_t tops[] = {PSX_STACK_TOP, 0x50800000u, 0x40800000u, 0x30800000u}; /* not 0x7xxxxxxx: literals */
    size_t i;
    for (i = 0; i < sizeof tops / sizeof tops[0]; i++) {
        void *p = psx_map(tops[i] - PSX_STACK_SIZE, PSX_STACK_SIZE);
        if (!p) continue;
        *bottom = tops[i] - PSX_STACK_SIZE;
        return (char *)p + PSX_STACK_SIZE;
    }
    return NULL;
}

static void on_stop(int sig) {
    psx_log("psx: %s after the time PSX_TIMEOUT gave\n", sig == SIGALRM ? "stopped" : "terminated");
    psx_exit_report();
    _exit(124);
}

static void run_main(void) {
    psx_log("psx: calling the game's main, %s\n", psx_config.main_name);
    psx_config.main_fn();
    psx_log("psx: %s returned\n", psx_config.main_name);
}

int main(int argc, char **argv) {
    const char *headless = getenv("PSX_HEADLESS");
    void *top;
    uint32_t bottom = 0;
    (void)argc; (void)argv;
    setvbuf(stdout, NULL, _IOLBF, 0);
    psx_log("psx: %s, generated by decomp.wtf's port export\n", psx_config.title);
    psx_dispatch_init();
    psx_ram_init();
    if (headless && *headless && strcmp(headless, "0") != 0) psx_log("psx: headless (PSX_HEADLESS)\n");
    else if (!host_init(psx_config.title, 640, 480)) psx_log("psx: no window (%s); running headless\n", host_name());
    else psx_log("psx: window 640x480 (%s)\n", host_name());
    atexit(psx_exit_report);
    signal(SIGTERM, on_stop);
    signal(SIGINT, on_stop);
    if (getenv("PSX_TIMEOUT") && atoi(getenv("PSX_TIMEOUT")) > 0) {
        signal(SIGALRM, on_stop);
        alarm((unsigned)atoi(getenv("PSX_TIMEOUT")));
    }
    if (getenv("PSX_GPU_SELFTEST") && atoi(getenv("PSX_GPU_SELFTEST")) > 0) {
        psx_gpu_selftest(atoi(getenv("PSX_GPU_SELFTEST")));
        exit(0);
    }
    top = game_stack(&bottom);
    if (!top) {
        fprintf(stderr, "psx: can't map the game's stack anywhere in the window\n");
        return 70;
    }
    psx_log("psx: game stack at PS1 0x%08X-0x%08X (host %p)\n", bottom, bottom + PSX_STACK_SIZE,
            (char *)top - PSX_STACK_SIZE);
    psx_call_on_stack(run_main, top);
    host_shutdown();
    return 0;
}
