#!/usr/bin/env python3
"""Build this decompilation and check the result against your own copy of the game, byte for byte.

    python build.py              extract what's needed from your copy (first run), build, compare
    python build.py check NAME   check one function's C (src/<segment>/NAME.c) against the original
    python build.py status       how many functions are C so far

Every function is its own object: C from src/<segment>/<name>.c when that file exists, otherwise the function's
assembly. game.ld (generated on every build from build.json) puts each one at its original address.
Generated by decomp.wtf (https://decomp.wtf). The build uses decomp.wtf's pinned period compilers and binutils.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
B = json.loads((ROOT / "build.json").read_text(encoding="utf-8"))
PREAMBLE = {
    "n64": '.include "macro.inc"\n.set noat\n.set noreorder\n.set gp=64\n.section .text, "ax"\n',
    "psx": '.include "macro.inc"\n.set noat\n.set noreorder\n.section .text, "ax"\n',
    "ps2": '.include "macro.inc"\n.set noat\n.set noreorder\n.section .text, "ax"\n',
}
OWN = ".rodata .rodata.* .data .data.* .sdata .rdata .lit4 .lit8 .bss .sbss"
PART = 200  # objects per partial link (see linker_script)
DISCARD = ("*(.reginfo) *(.MIPS.abiflags) *(.MIPS.options) *(.pdr) *(.comment) *(.mdebug*) *(.gnu.attributes) "
           "*(.note*) *(.gptab.*)")

try:
    from decompnet import toolchains
    from decompnet.compiler import run_in
    from decompnet.project import compiler_config, with_toolchain
except ImportError:
    sys.exit("This build uses decomp.wtf's pinned compilers: install decomp.wtf first (https://decomp.wtf).")


def fail(msg: str) -> None:
    sys.exit(f"error: {msg}")


def run(argv: list[str]) -> None:
    res = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if res.returncode != 0:
        fail(f"{' '.join(argv[:3])} ...\n{(res.stdout + res.stderr)[-3000:]}")


def binutils(tool: str) -> str:
    toolchains.ensure("binutils-mips", log=lambda *_: None)
    return str(toolchains.binary("binutils-mips").parent / f"mips-ps2-decompals-{tool}")


def sha1(path: Path) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()


def setup() -> None:
    base = ROOT / B["image"]
    if not base.exists():
        fail(f"put your own copy of the game here as {B['image']} (see README.md)")
    if sha1(base) != B["sha1"]:
        fail(f"{B['image']} isn't the version this project decompiles (its SHA-1 differs)")
    if not (ROOT / "asm" / "nonmatchings").exists():
        print("extracting the assembly and data from your copy (splat)")
        run([sys.executable, "-m", "splat", "split", "splat.yaml"])
        for generated in (ROOT / "src").glob("*.c"):
            generated.unlink()  # splat's INCLUDE_ASM files; this tree builds one object per function
    for seg in B["segments"]:
        if seg.get("incbin"):
            stub = ROOT / seg["stub"]
            stub.parent.mkdir(parents=True, exist_ok=True)
            stub.write_text(f'.section .data\n.incbin "{seg["incbin"]}"\n', encoding="utf-8")


def c_source(fn: dict) -> str | None:
    path = fn.get("c") or f"src/{fn['seg']}/{fn['name']}.c"
    return path if (ROOT / path).exists() else None


def key(fn: dict) -> str:
    """A function's segment and name: overlays loaded at the same address have functions with the same names."""
    return f"{fn['seg']}/{fn['name']}"


def objects(as_asm: frozenset[str] = frozenset()) -> tuple[list[tuple[str, str, str]], dict[str, str]]:
    """[(kind, source, object)] to build, and function (key()) -> the object that provides it. Functions in `as_asm`
    are built from their assembly even when they have C."""
    out, provides = [], {}
    for a in B["assembly"]:
        out.append(("asm", a["src"], a["obj"]))
    for fn in B["functions"]:
        c = c_source(fn) if key(fn) not in as_asm else None
        if c:
            obj = f"build/{Path(c).with_suffix('.o').as_posix()}"
            out.append(("c", c, obj))
        else:
            wrap = ROOT / "build" / "wrap" / fn["seg"] / f"{fn['name']}.s"
            wrap.parent.mkdir(parents=True, exist_ok=True)
            wrap.write_text(PREAMBLE[B["platform"]] + f'.include "{fn["asm"]}"\n', encoding="utf-8")
            obj = f"build/{Path(fn['asm']).with_suffix('.o').as_posix()}"
            out.append(("asm", wrap.relative_to(ROOT).as_posix(), obj))
        provides[key(fn)] = obj
    return out, provides


def trim(path: Path) -> None:
    """Shrink a compiled object's code section to where its last function ends. Period assemblers pad sections to
    16 bytes; with every function placed at its own address, that padding would run into the next function."""
    import struct
    from io import BytesIO

    from elftools.elf.elffile import ELFFile

    from decompnet.elfobj import _function_symbols

    data = bytearray(path.read_bytes())
    elf = ELFFile(BytesIO(bytes(data)))
    ends: dict[int, int] = {}
    for shndx, off, size in _function_symbols(elf).values():
        ends[shndx] = max(ends.get(shndx, 0), off + size)
    order = ">" if data[5] == 2 else "<"
    shoff = struct.unpack_from(order + "I", data, 0x20)[0]
    shentsize = struct.unpack_from(order + "H", data, 0x2E)[0]
    for shndx, end in ends.items():
        sec = elf.get_section(shndx)
        tail = sec.data()[end:]
        relocated = any(r["r_offset"] >= end for rs in elf.iter_sections()
                        if rs.header["sh_type"] in ("SHT_REL", "SHT_RELA") and rs["sh_info"] == shndx
                        for r in rs.iter_relocations())
        if end < sec["sh_size"] and not tail.strip(b"\0") and not relocated:
            struct.pack_into(order + "I", data, shoff + shndx * shentsize + 20, end)
    path.write_bytes(bytes(data))


def as_bytes(path: Path) -> str:
    """A function's assembly with each instruction replaced by its bytes, from splat's /* rom vram bytes */ comments."""
    out = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"\s*/\*\s*[0-9A-Fa-f]+\s+[0-9A-Fa-f]{8}\s+([0-9A-Fa-f]{8})\s*\*/", line)
        if m:
            out.append(".byte " + ", ".join(f"0x{m.group(1)[i:i + 2]}" for i in range(0, 8, 2)))
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def compiler_for(fn: dict | None):
    """The project's compiler, or the function's own (a game built with two compiler versions)."""
    return compiler_config(ROOT, {"compiler": with_toolchain(B["compiler"], (fn or {}).get("toolchain"))})


def build_objects(todo: list[tuple[str, str, str]]) -> None:
    from concurrent.futures import ThreadPoolExecutor

    owner = {c_source(fn): fn for fn in B["functions"] if fn.get("toolchain")}
    cfgs = {}
    as_ = binutils("as")
    headers = max((h.stat().st_mtime for h in (ROOT / "include").glob("**/*") if h.is_file()), default=0)
    compiles = []
    for kind, src, obj in todo:
        target = ROOT / obj
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists() and target.stat().st_mtime > max((ROOT / src).stat().st_mtime,
                                                             headers if kind == "c" else 0):
            continue
        if kind == "asm":
            res = subprocess.run([as_, *B["as_flags"], "-o", obj, src], cwd=ROOT, capture_output=True, text=True,
                                 encoding="utf-8", errors="replace")
            if res.returncode != 0 and src.startswith("build/wrap/"):
                # instructions this processor doesn't have (data splat took for code): the bytes as they are
                original = re.search(r'\.include "([^"]+)"\s*$', (ROOT / src).read_text(encoding="utf-8")).group(1)
                (ROOT / src).write_text(PREAMBLE[B["platform"]] + as_bytes(ROOT / original), encoding="utf-8")
                res = subprocess.run([as_, *B["as_flags"], "-o", obj, src], cwd=ROOT, capture_output=True, text=True,
                                     encoding="utf-8", errors="replace")
            if res.returncode != 0:
                fail(f"assembling {src} failed:\n{(res.stdout + res.stderr)[-3000:]}")
        else:
            fn = owner.get(src)
            if (key := src if fn else None) not in cfgs:
                cfgs[key] = compiler_for(fn)
            compiles.append((cfgs[key], src, obj))

    def compile_one(job) -> str | None:
        cfg, src, obj = job
        argv = [a.replace("{src}", src).replace("{obj}", obj).replace("{include}", "include") for a in cfg.cmd]
        res = run_in(cfg, ROOT, argv, inputs=[src, "include"], outputs=[obj])
        if res.returncode != 0 or not (ROOT / obj).exists():
            return f"compiling {src} failed:\n{(res.stdout + res.stderr)[-3000:]}"
        trim(ROOT / obj)
        return None

    if compiles:
        print(f"compiling {len(compiles)} C files")
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        for err in pool.map(compile_one, compiles):
            if err:
                fail(err)


def _size(obj: str, sections: tuple[str, ...]) -> int:
    from elftools.elf.elffile import ELFFile

    with open(ROOT / obj, "rb") as f:
        elf = ELFFile(f)
        return sum(s["sh_size"] for s in elf.iter_sections() if s.name in sections and s["sh_type"] != "SHT_NOBITS")


def fill_gaps(provides: dict[str, str]) -> list[tuple[int, str]]:
    """Bytes of a code segment no object covers (a splitter can miss a few at an odd segment end): assemble them
    from your copy of the game, so the build never depends on what the splitter got exactly right."""
    image = (ROOT / B["image"]).read_bytes()
    extra = []
    for seg in B["segments"]:
        if seg["kind"] != "code":
            continue
        end = seg["end"] if seg["end"] is not None else len(image)
        covered = [(p["vram"], _size(p["obj"], (".text", ".data", ".rodata", ".sdata", ".rdata"))) for p in seg["pieces"]]
        covered += [(fn["vram"], _size(provides[key(fn)], (".text",))) for fn in B["functions"]
                    if fn["rom"] is not None and seg["start"] <= fn["rom"] < end]
        pos = seg["vram"]
        for vram, size in sorted(covered) + [(seg["vram"] + end - seg["start"], 0)]:
            if vram > pos:
                raw = image[seg["start"] + pos - seg["vram"]:seg["start"] + vram - seg["vram"]]
                if raw.strip(b"\0"):
                    src = ROOT / "build" / "gaps" / f"{pos:08X}.s"
                    src.parent.mkdir(parents=True, exist_ok=True)
                    src.write_text(".section .data\n" + "".join(f".byte {', '.join(str(b) for b in raw[i:i + 16])}\n"
                                                              for i in range(0, len(raw), 16)), encoding="utf-8")
                    obj = f"build/gaps/{pos:08X}.o"
                    run([binutils("as"), *B["as_flags"], "-o", obj, src.relative_to(ROOT).as_posix()])
                    extra.append((pos, obj))
            pos = max(pos, vram + size)
    return extra


def linker_script(provides: dict[str, str], gaps: list[tuple[int, str]], segments: list[dict] | None = None,
                  elsewhere: dict[str, int] | None = None, fixed: dict[str, int] | None = None,
                  inputs: dict[str, str] | None = None) -> str:
    """The linker script for `segments` (default: all of them); `elsewhere`: what the other links define, for the
    names these segments use from them (an overlay calling into the main program, the main program into an overlay);
    `fixed`: names defined outright (the main program's, in an overlay's link). Objects partially linked into one
    are recorded in `inputs` (object -> the partial link that holds it): the final link takes that one instead."""
    segments = B["segments"] if segments is None else segments
    names = {seg["name"] for seg in segments}
    owns = {}  # C object -> [(section, base)]: its own data, placed where the matcher found it
    for fn in B["functions"]:
        if key(fn) in provides and provides[key(fn)].startswith("build/src/") and fn["seg"] in names:
            owns[provides[key(fn)]] = list((fn.get("own") or {}).items())
    placed = []  # (object, section, base) for the .own_ sections: filled in by partial()
    if inputs is None:
        inputs = {}

    def partial(name: str, items: list[tuple[int, str, str]], owns: dict) -> list[tuple[int, str, str]]:
        """Consecutive objects partially linked (ld -r) into one, PART at a time: this ld's section matching gets
        much slower with the number of input files (4,300 objects take 10 minutes in one link, 200 a fraction of
        a second). Each C object's own data keeps a section of its own, for the final link to place."""
        out = []
        for k in range(0, len(items), PART):
            run_ = items[k:k + PART]
            first = run_[0][0]
            obj = f"build/part/{name}_{k // PART}.o"
            script = ["SECTIONS", "{", "    .part 0 : SUBALIGN(4)", "    {"]
            script += [f"        . = 0x{v - first:X}; {o}({what})" for v, o, what in run_]
            script.append("    }")
            for _, o, _ in run_:
                for section, base in owns.get(o, []):
                    renamed = f".own_{len(placed)}"
                    script.append(f"    {renamed} 0 : SUBALIGN(1) {{ {o}({section}) }}")
                    placed.append((obj, renamed, base))
            script += ["}", ""]
            (ROOT / "build" / "part").mkdir(parents=True, exist_ok=True)
            (ROOT / obj).with_suffix(".ld").write_text("\n".join(script), encoding="utf-8")
            run([binutils("ld"), *B["ld_flags"], "-r", "-T", Path(obj).with_suffix(".ld").as_posix(), "-o", obj,
                 *dict.fromkeys(o for _, o, _ in run_)])
            out.append((first, obj, ".part"))
            inputs.update((o, obj) for _, o, _ in run_)
        return out

    lines = ["/* Generated by build.py from build.json: every function and data block at its original address. */",
             "SECTIONS", "{"]
    for seg in segments:
        if seg["kind"] == "raw":
            objs = " ".join(f"{o}(.data .text .rodata)" for o in seg["objects"])
            lines.append(f"    .{seg['name']} 0x{seg['start']:X} : AT(0x{seg['start']:X}) {{ {objs} }}")
            continue
        vram, start = seg["vram"], seg["start"]
        end = seg["end"] if seg["end"] is not None else 1 << 32
        items = [(p["vram"], p["obj"], ".text .data .rodata .sdata .rdata") for p in seg["pieces"]]
        items += [(v, obj, ".data") for v, obj in gaps if vram <= v < vram + end - start]
        for fn in B["functions"]:
            if fn["rom"] is not None and start <= fn["rom"] < end:
                items.append((fn["vram"], provides[key(fn)], ".text"))
        lines += [f"    .{seg['name']} 0x{vram:08X} : AT(0x{start:X}) SUBALIGN(4)", "    {"]
        lines += [f"        . = 0x{v - vram:X}; {obj}({what})" for v, obj, what in partial(seg["name"], sorted(items), owns)]
        lines.append("    }")
        if seg["bss"]:
            bss_vram = seg["bss"][0]["vram"]
            lines += [f"    .{seg['name']}_bss 0x{bss_vram:08X} (NOLOAD) : SUBALIGN(4)", "    {"]
            lines += [f"        . = 0x{b['vram'] - bss_vram:X}; {b['obj']}(.bss .sbss)" for b in seg["bss"]]
            lines.append("    }")
    for n, (obj, section, base) in enumerate(placed):
        # SUBALIGN(1): at the address the matcher found, not moved up to the section's alignment (a jump table GCC
        # aligns to 8 at an address that's 4 past one)
        lines.append(f"    .own_{n} 0x{base:08X} (NOLOAD) : SUBALIGN(1) {{ {obj}({section}) }}")
    # own data of C functions nobody placed yet: kept out of the image; `build.py check` places it
    lines.append(f"    .unplaced 0xF0000000 (NOLOAD) : {{ build/src/*({OWN}) build/part/*({OWN}) }}")
    lines += [f"    /DISCARD/ : {{ {DISCARD} }}", "}", ""]
    if B.get("gp"):
        lines.append(f"_gp = 0x{B['gp']:08X};")
    lines += [f"{name} = 0x{addr:08X};" for name, addr in B["symbols"].items()]
    # jump tables in the data point at labels inside functions (.L001006F8); with one object per function those
    # labels are local to another object, so give them their addresses (which their names spell out)
    # (and a branch into another function's label: splat split one routine in two)
    lines += [f'".L{label}" = 0x{label};' for label in sorted(_cross_labels())]
    # an auto-named symbol a function uses that its link doesn't define (inside a bigger data block, or another
    # overlay's): where its name says
    lines += [f"PROVIDE({name} = 0x{name.rsplit('_', 1)[1]});" for name in sorted(_spelled_names(provides) - set(elsewhere or {}) - set(fixed or {}))]
    lines += [f"PROVIDE({name} = 0x{addr:08X});" for name, addr in sorted((elsewhere or {}).items())]
    lines += [f"{name} = 0x{addr:08X};" for name, addr in sorted((fixed or {}).items()) if name not in B["symbols"]]
    # the segment symbols splat projects use (start-up code clears .bss with them)
    image_size = (ROOT / B["image"]).stat().st_size
    for seg in B["segments"]:
        n, start = seg["name"], seg["start"]
        end = seg.get("end") if seg.get("end") is not None else image_size
        lines += [f"{n}_ROM_START = 0x{start:X};", f"{n}_ROM_END = 0x{end:X};"]
        if seg["kind"] == "code":
            vram = seg["vram"]
            bss_start = seg.get("bss_vram") or vram + end - start
            bss_end = bss_start + seg.get("bss_size", 0)
            lines += [f"{n}_VRAM = 0x{vram:08X};", f"{n}_VRAM_END = 0x{bss_end:08X};",
                      f"{n}_BSS_START = 0x{bss_start:08X};", f"{n}_BSS_END = 0x{bss_end:08X};",
                      f"{n}_BSS_SIZE = 0x{bss_end - bss_start:X};"]
    return "\n".join(lines) + "\n"


def _code(seg: dict, image_size: int) -> tuple[int, int]:
    return seg["vram"], seg["vram"] + (seg["end"] if seg["end"] is not None else image_size) - seg["start"]


_CACHE: dict[str, set[str]] = {}


def _cross_labels() -> set[str]:
    if "labels" not in _CACHE:
        found = set()
        for path in (ROOT / "asm").glob("**/*.s"):
            text = path.read_text(errors="replace", encoding="utf-8")
            if path.is_relative_to(ROOT / "asm" / "data"):
                found.update(re.findall(r"\.word\s+\.L([0-9A-Fa-f]{8})\b", text))
            else:
                here = set(re.findall(r"^\s*\.L([0-9A-Fa-f]{8}):", text, re.M))
                found.update(set(re.findall(r"\.L([0-9A-Fa-f]{8})\b", text)) - here)
        _CACHE["labels"] = found
    return _CACHE["labels"]


def _spelled_names(provides: dict[str, str]) -> set[str]:
    key = "spelled" + str(len(provides))
    if key not in _CACHE:
        found = set()
        sources = [ROOT / Path(obj).relative_to("build").with_suffix(".c") for obj in set(provides.values())
                   if obj.startswith("build/src/")] + list((ROOT / "asm" / "nonmatchings").glob("**/*.s"))
        for src in sources:
            found.update(re.findall(r"\b(?:D|func|jtbl)_[0-9A-F]{8}\b", src.read_text(errors="replace", encoding="utf-8")))
        _CACHE[key] = found - set(B["symbols"])
    return _CACHE[key]


def links() -> list[list[dict]]:
    """The segments linked together. One link for everything, unless code segments share addresses (overlays loaded
    at the same place in turn): then each of those is its own link, and the rest go with the first."""
    size = (ROOT / B["image"]).stat().st_size
    code = [seg for seg in B["segments"] if seg["kind"] == "code"]
    spans = [_code(seg, size) for seg in code]
    if not any(a[0] < b[1] and b[0] < a[1] for i, a in enumerate(spans) for b in spans[i + 1:]):
        return [B["segments"]]
    return [[seg for seg in B["segments"] if seg["kind"] != "code"] + code[:1]] + [[seg] for seg in code[1:]]


_LABEL = re.compile(r"^\s*(?:glabel|dlabel|jlabel)\s+(\w+)\s*\n\s*/\*\s*[0-9A-Fa-f]+\s+([0-9A-Fa-f]{8})\s", re.M)


def _labels(src: str) -> dict[str, int]:
    text = (ROOT / src).read_text(encoding="utf-8", errors="replace")
    for inc in re.findall(r'\.include "([^"]+)"', text):  # a function's wrapper: its assembly
        if inc != "macro.inc":
            text += (ROOT / inc).read_text(encoding="utf-8", errors="replace")
    return {m.group(1): int(m.group(2), 16) for m in _LABEL.finditer(text)}


def oversized(provides: dict[str, str]) -> list[tuple[str, int, int]]:
    """C functions whose code is longer than the room before the next function or data block: (name, size, room)."""
    image_size = (ROOT / B["image"]).stat().st_size
    out = []
    for seg in B["segments"]:
        if seg["kind"] != "code":
            continue
        end = _code(seg, image_size)[1]
        at = sorted({p["vram"] for p in seg["pieces"]} | {fn["vram"] for fn in B["functions"]
                                                          if fn["rom"] is not None and seg["name"] == fn["seg"]} | {end})
        for fn in B["functions"]:
            obj = provides.get(key(fn), "")
            if fn["seg"] != seg["name"] or not obj.startswith("build/src/"):
                continue
            room = next(a for a in at if a > fn["vram"]) - fn["vram"]
            if (size := _size(obj, (".text",))) > room:
                out.append((key(fn), size, room))
    return out


def build() -> bool:
    setup()
    todo, provides = objects()
    build_objects(todo)
    too_big = oversized(provides)
    if too_big:  # its object holds more than the function (and would overwrite what follows): its assembly instead
        for name, size, room in too_big:
            print(f"warning: {name}'s C compiles to 0x{size:X} bytes, 0x{room:X} fit: built from its assembly")
        todo, provides = objects(frozenset(name for name, _, _ in too_big))
        build_objects(todo)
    gaps = fill_gaps(provides)
    if gaps:
        print(f"note: {len(gaps)} stretches no function or data block covers were copied from {B['image']}")
    groups = links()
    # which link each object goes into: its segment's; assembly that isn't in any segment goes with the first
    seg_of = {}
    for seg in B["segments"]:
        for o in seg.get("objects", []):
            seg_of[o] = seg["name"]
        for piece in seg.get("pieces", []) + seg.get("bss", []):
            seg_of[piece["obj"]] = seg["name"]
    for fn in B["functions"]:
        seg_of[provides[key(fn)]] = fn["seg"]
    image_size = (ROOT / B["image"]).stat().st_size
    for vram, obj in gaps:
        seg_of[obj] = next(seg["name"] for seg in B["segments"] if seg["kind"] == "code"
                           and _code(seg, image_size)[0] <= vram < _code(seg, image_size)[1])
    group_of = {seg["name"]: i for i, group in enumerate(groups) for seg in group}
    srcs = {obj: src for _, src, obj in todo}
    members: list[list[str]] = [[] for _ in groups]
    for obj in sorted({obj for _, _, obj in todo} | {obj for _, obj in gaps}):
        members[group_of.get(seg_of.get(obj, ""), 0)].append(obj)
    defined = [{} for _ in groups]  # the labels each link defines, for the others' PROVIDEs
    if len(groups) > 1:
        for i, objs in enumerate(members):
            for obj in objs:
                if obj in srcs and not srcs[obj].endswith(".c"):
                    defined[i].update(_labels(srcs[obj]))
        for fn in B["functions"]:
            defined[group_of.get(fn["seg"], 0)][fn["name"]] = fn["vram"]
    out = bytearray()
    for i, group in enumerate(groups):
        tag = "game" if len(groups) == 1 else f"game.{group[-1]['name']}"
        elsewhere = {}
        for j, other in enumerate(defined):
            if j != i:
                for name, addr in other.items():
                    elsewhere.setdefault(name, addr)
        for name in defined[i]:
            elsewhere.pop(name, None)
        # an overlay gets the main program's names as definitions, not PROVIDEs: a variable the shared header declares
        # without `extern` is a common in every C object, and only a definition puts it where the main program has it
        fixed = {name: addr for name, addr in defined[0].items() if name not in defined[i]} if i else {}
        for name in fixed:
            elsewhere.pop(name, None)
        inputs: dict[str, str] = {}
        (ROOT / "build" / f"{tag}.ld").write_text(linker_script(provides, gaps, group, elsewhere, fixed, inputs),
                                                  encoding="utf-8")
        objs = list(dict.fromkeys(inputs.get(o, o) for o in members[i]))
        run([binutils("ld"), *B["ld_flags"], "-T", f"build/{tag}.ld", "-o", f"build/{tag}.elf", *objs])
        run([binutils("objcopy"), "-O", "binary", f"build/{tag}.elf", f"build/{tag}.bin"])
        part = (ROOT / "build" / f"{tag}.bin").read_bytes()
        at = min(seg["start"] for seg in group)
        if len(out) < at + len(part):
            out.extend(bytes(at + len(part) - len(out)))
        out[at:at + len(part)] = part
    base = (ROOT / B["image"]).read_bytes()
    if len(out) < len(base) and not base[len(out):].strip(b"\0"):
        out.extend(bytes(len(base) - len(out)))  # the image's zero padding at the end
    (ROOT / B["output"]).write_bytes(bytes(out))
    c_count = sum(1 for p in provides.values() if p.startswith("build/src/"))
    write_report(out, base, provides, too_big)
    if out == base:
        print(f"identical: {B['output']} matches {B['image']} byte for byte "
              f"({c_count} of {len(B['functions'])} functions in C)")
        return True
    at = next((i for i in range(min(len(out), len(base))) if out[i] != base[i]), min(len(out), len(base)))
    where = next((fn["name"] for fn in sorted(B["functions"], key=lambda f: f["rom"] or 0, reverse=True)
                  if fn["rom"] is not None and fn["rom"] <= at), "?")
    print(f"differs: first difference at offset 0x{at:X} (in or after {where}); sizes {len(out)} vs {len(base)}")
    return False


def write_report(out: bytes | bytearray, base: bytes, provides: dict[str, str], too_big: list) -> None:
    """build/report.json, for tools (decomp.wtf reads it): identical or not, the C that didn't fit its place, and
    every function whose bytes differ (where first, how many, whether it's C)."""
    import bisect

    fns = sorted((fn for fn in B["functions"] if fn["rom"] is not None), key=lambda fn: fn["rom"])
    roms = [fn["rom"] for fn in fns]
    differs: dict[str, dict] = {}
    for i in (i for i in range(min(len(out), len(base))) if out[i] != base[i]):
        k = bisect.bisect_right(roms, i) - 1
        if k < 0:
            continue
        fn = fns[k]
        d = differs.setdefault(key(fn), {"seg": fn["seg"], "name": fn["name"], "offset": i, "bytes": 0,
                                         "c": provides.get(key(fn), "").startswith("build/src/")})
        d["bytes"] += 1
    report = {"identical": out == base, "size": len(out), "original_size": len(base),
              "c": sum(1 for p in provides.values() if p.startswith("build/src/")), "functions": len(B["functions"]),
              "too_big": [{"seg": k.split("/", 1)[0], "name": k.split("/", 1)[1], "size": size, "room": room}
                          for k, size, room in too_big],
              "differs": list(differs.values())}
    (ROOT / "build" / "report.json").write_text(json.dumps(report, indent=1), encoding="utf-8")


def check(name: str) -> bool:
    """Compile one function and link it at its address with decomp.wtf's matcher; record where its data goes."""
    from decompnet.compiler import compile_source
    from decompnet.rom import match, split
    from decompnet.rom.symbols import Symbol, SymbolTable

    setup()
    fn = next((f for f in B["functions"] if f["name"] == name), None)
    if fn is None:
        fail(f"no function {name}")
    src = c_source(fn)
    if not src:
        fail(f"write it first as src/{fn['seg']}/{name}.c")
    found = [Symbol(s, a, 0, "data") for s, a in B["symbols"].items()]
    found += [Symbol(f["name"], f["vram"], 0, "func") for f in B["functions"]]
    for path in (ROOT / "asm" / "data").glob("**/*.s"):
        text = path.read_text(errors="replace", encoding="utf-8")
        for m in re.finditer(r"dlabel (\w+)\s*\n\s*/\*\s*(?:[0-9A-F]+\s+)?([0-9A-F]{8})", text):
            found.append(Symbol(m.group(1), int(m.group(2), 16), 0, "data"))
    table = SymbolTable(found)
    big = B["big_endian"]
    rf = split.parse_function(ROOT / fn["asm"], fn["seg"], big)
    target = match.target_from_split(rf, table.resolve, big, B.get("gp") or 0)
    image = (ROOT / B["image"]).read_bytes()

    def read(addr: int, n: int) -> bytes | None:
        for seg in B["segments"]:
            if seg["kind"] == "code":
                size = (seg["end"] if seg["end"] is not None else len(image)) - seg["start"]
                if seg["vram"] <= addr and addr + n <= seg["vram"] + size:
                    at = seg["start"] + addr - seg["vram"]
                    return image[at:at + n]
        return None

    cfg = compiler_for(fn)
    text = (ROOT / src).read_text(encoding="utf-8")
    m = re.match(r'\s*#include "([^"]+)"\s*\n', text)
    header = (ROOT / "include" / m.group(1)).read_text(encoding="utf-8") if m else ""
    res = compile_source(cfg, header, text[m.end():] if m else text, trusted=True)
    if not res.ok:
        print(res.log)
        return False
    linked = match.link(res.obj, name, target, table, read)
    if not linked.exact:
        print(f"{name}: not identical yet")
        for p in linked.problems:
            print(f"  - {p}")
        return False
    fn["c"] = src
    fn["own"] = {sec: min(a - o for o, a in offs.items()) for sec, offs in linked.placements.items()}
    (ROOT / "build.json").write_text(json.dumps(B, indent=1), encoding="utf-8")
    print(f"{name}: identical to the original; recorded in build.json")
    return True


def status() -> None:
    c = [fn["name"] for fn in B["functions"] if c_source(fn)]
    print(f"{len(c)} of {len(B['functions'])} functions are C ({100 * len(c) / max(1, len(B['functions'])):.1f}%)")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args[:1] == ["check"] and len(args) == 2:
        sys.exit(0 if check(args[1]) else 1)
    if args[:1] == ["status"]:
        status()
        sys.exit(0)
    sys.exit(0 if build() else 1)
